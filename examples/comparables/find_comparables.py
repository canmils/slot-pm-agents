"""Comparables agent example: show how past games like a new option performed, as a range.

Runs on the same normalised data as examples/portfolio_review (GGR at fixed ages).
Never gives a single forecast. No model key needed.
"""
import argparse
import importlib.util
import json
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PORTFOLIO = HERE.parent / "portfolio_review"

ALLOWED = ["family", "mechanic", "volatility", "theme", "type", "vendor", "exclusive", "seasonal"]
WINDOWS = [30, 90, 180]
MIN_COMPARABLES = 3


def _analyze():
    spec = importlib.util.spec_from_file_location("analyze", PORTFOLIO / "analyze.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def load_games(config_path: Path) -> tuple[list[dict], dict]:
    cfg = json.loads(config_path.read_text(encoding="utf-8"))
    _, summary = _analyze().build(cfg)
    return summary["games"], summary


def validate_option(option: dict) -> list[tuple[str, object]]:
    criteria = option.get("criteria")
    if not isinstance(criteria, dict) or not criteria:
        raise ValueError("option.json needs a non-empty 'criteria' object, most important criterion first.")
    unknown = [k for k in criteria if k not in ALLOWED]
    if unknown:
        raise ValueError(f"Unknown criteria {unknown}. Allowed: {ALLOWED}")
    return list(criteria.items())


def find(games: list[dict], criteria: list[tuple[str, object]]) -> tuple[list[dict], list[str]]:
    """Match on all criteria. If fewer than MIN_COMPARABLES match, drop the least
    important criterion (the last one) and try again. Return matches and dropped criteria."""
    dropped: list[str] = []
    active = list(criteria)
    while active:
        matches = [g for g in games if all(g.get(k) == v for k, v in active)]
        if len(matches) >= MIN_COMPARABLES or len(active) == 1:
            return matches, dropped
        key, _ = active.pop()
        dropped.append(key)
    return [], dropped


def ranges(matches: list[dict]) -> list[dict]:
    rows = []
    for w in WINDOWS:
        values = [g[f"ggr_{w}d"] for g in matches if g.get(f"ggr_{w}d") is not None]
        rows.append({
            "window_days": w,
            "games": len(values),
            "low": min(values) if values else None,
            "median": statistics.median(values) if values else None,
            "high": max(values) if values else None,
        })
    for field, label in [("actual_eur", "cost_eur"), ("weeks_actual", "weeks_actual")]:
        values = [g[field] for g in matches if g.get(field) is not None]
        rows.append({"measure": label, "games": len(values),
                     "low": min(values) if values else None,
                     "median": statistics.median(values) if values else None,
                     "high": max(values) if values else None})
    return rows


def _k(v):
    return "not yet" if v is None else f"{v / 1000:,.0f}k"


def report(option: dict, criteria, matches, dropped, rng, summary) -> str:
    used = [f"{k} = {v}" for k, v in criteria if k not in dropped]
    lines = [
        f"# Comparables: {option.get('name', 'new option')}",
        "",
        f"Data up to **{summary['data_date']}**. Input label: {summary['data_label']}. "
        "GGR is compared at the same age after launch.",
        "",
        "> Generated by find_comparables.py. This is a range of past results, not a forecast.",
        "",
        "## Matching",
        "",
        f"- Criteria used: {', '.join(used) if used else 'none'}",
    ]
    if dropped:
        lines.append(f"- Dropped to reach {MIN_COMPARABLES} games (least important first): {', '.join(dropped)}")
    lines.append(f"- Comparable games found: **{len(matches)}**")
    if len(matches) < MIN_COMPARABLES:
        lines += ["", f"**Warning: fewer than {MIN_COMPARABLES} comparable games. Do not base a decision on this range.**"]
    lines += ["", "## Range", "", "| Measure | Games | Low | Median | High |", "|---|---|---|---|---|"]
    for r in rng:
        if "window_days" in r:
            lines.append(f"| GGR at {r['window_days']} days | {r['games']} | {_k(r['low'])} | {_k(r['median'])} | {_k(r['high'])} |")
        elif r["measure"] == "cost_eur":
            lines.append(f"| Actual cost | {r['games']} | {_k(r['low'])} | {_k(r['median'])} | {_k(r['high'])} |")
        else:
            fmt = lambda v: "n/a" if v is None else f"{v:.1f}"  # noqa: E731
            lines.append(f"| Weeks to launch | {r['games']} | {fmt(r['low'])} | {fmt(r['median'])} | {fmt(r['high'])} |")
    thin = [f"GGR at {r['window_days']} days" for r in rng if "window_days" in r and r["games"] < MIN_COMPARABLES]
    if thin:
        lines += ["", f"**Fewer than {MIN_COMPARABLES} games old enough for: {', '.join(thin)}. Treat these rows as anecdotes.**"]
    lines += ["", "## Games", "", "| Game | Type | Vendor | Days live | GGR 30d | GGR 90d | GGR 180d | Break-even day |",
              "|---|---|---|---|---|---|---|---|"]
    for g in sorted(matches, key=lambda g: -(g.get("ggr_90d") or -1)):
        be = "not reached" if g.get("break_even_day") is None else str(int(g["break_even_day"]))
        lines.append(f"| {g['title']} | {g['type']} | {g['vendor']} | {g['days_live']} | {_k(g.get('ggr_30d'))} | "
                     f"{_k(g.get('ggr_90d'))} | {_k(g.get('ggr_180d'))} | {be} |")
    lines += ["", "## Uncertainty", ""]
    families = {g["family"] for g in matches}
    if len(matches) > 1 and len(families) == 1:
        lines.append(f"- **All comparables are from one family ({families.pop()}).** "
                     "The range may reflect that family, not the criteria.")
    lines += ["- A few games make most of the money, so results near the high end are rare.",
              "- Matching on a few attributes does not control for theme quality, distribution, operators or season.",
              "- \"not yet\" means the game is younger than that window. It is not zero.",
              "- Break-even uses the configured revenue share and recorded cost. It is not net profit.",
              "", "## Decision", "", "Product Lead decides if this range justifies the cost. This report does not recommend."]
    return "\n".join(lines) + "\n"


def run(option_path: Path, config_path: Path) -> tuple[str, dict]:
    option = json.loads(option_path.read_text(encoding="utf-8"))
    criteria = validate_option(option)
    games, summary = load_games(config_path)
    matches, dropped = find(games, criteria)
    rng = ranges(matches)
    result = {"option": option, "dropped_criteria": dropped,
              "comparables": [g["game_id"] for g in matches], "ranges": rng,
              "data_date": summary["data_date"], "data_label": summary["data_label"]}
    return report(option, criteria, matches, dropped, rng, summary), result


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--option", type=Path, default=HERE / "option.json")
    ap.add_argument("--config", type=Path, default=PORTFOLIO / "config.json")
    ap.add_argument("--output-dir", type=Path, required=True)
    ap.add_argument("--overwrite", action="store_true")
    args = ap.parse_args(argv)
    outputs = [args.output_dir / "comparables.md", args.output_dir / "comparables.json"]
    if not args.overwrite and any(p.exists() for p in outputs):
        ap.error("Output already exists. Choose a new --output-dir or use --overwrite.")
    try:
        md, result = run(args.option, args.config)
    except ValueError as exc:
        print(f"Error: {exc}")
        return 1
    args.output_dir.mkdir(parents=True, exist_ok=True)
    outputs[0].write_text(md, encoding="utf-8")
    outputs[1].write_text(json.dumps(result, indent=2, allow_nan=False), encoding="utf-8")
    print(f"Wrote {outputs[0]} and {outputs[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
